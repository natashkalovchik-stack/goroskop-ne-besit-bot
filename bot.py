        name = profile.get("name")
        sign = profile.get("sign")
        if not (name and sign):
            await query.message.reply_text(
                "Чтобы подсмотреть твою персональную неделю, мне нужно немного "
                "больше о тебе узнать 🫶\n\n"
                "Пройди мини-анкету через меню: «📝 Мини-анкета»."
            )
            return
