# ---------- CallbackQuery handler ----------

async def handle_callback(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    query = update.callback_query
    data = query.data
    user_data = context.user_data
    profile = get_profile(user_data)
    await query.answer()

    # ----- Навигация -----
    if data == "BACK_MAIN":
        await query.message.reply_text(
            "Возвращаемся в главное меню 🏠",
            reply_markup=get_main_menu_keyboard(),
        )
        return

    if data == "BACK_UTILS":
        await query.message.reply_text(
            "Полезности и советы 🌿",
            reply_markup=get_utils_menu_keyboard(),
        )
        return

    # ----- Гороскоп: меню -----
    if data == "HORO_PICK_SIGN":
        await query.message.reply_text(
            "Выбери свой знак зодиака ✨",
            reply_markup=get_zodiac_inline_keyboard("HORO_SIGN_"),
        )
        return

    if data == "HORO_TODAY":
        sign = profile.get("sign")
        if not sign:
            await query.message.reply_text(
                "Сначала давай выберем твой знак ✨",
                reply_markup=get_zodiac_inline_keyboard("HORO_SIGN_"),
            )
            return
        text = choose_random_text(HOROSCOPE_TODAY_TEXTS, user_data)
        await query.message.reply_text(f"🔮 Гороскоп на сегодня:\n\n{text}")
        return

    if data == "HORO_WEEK":
        sign = profile.get("sign")
        if not sign:
            await query.message.reply_text(
                "Сначала давай выберем твой знак ✨",
                reply_markup=get_zodiac_inline_keyboard("HORO_SIGN_"),
            )
            return
        text = choose_random_text(HOROSCOPE_WEEK_TEXTS, user_data)
        await query.message.reply_text(f"📅 Гороскоп на неделю:\n\n{text}")
        return

    # ----- Выбор знака: из гороскопа -----
    if data.startswith("HORO_SIGN_"):
        sign_code = data.replace("HORO_SIGN_", "")
        # Найдём красивый вид знака по коду
        pretty = next(
            (label for (label, code) in ZODIAC_SIGNS if code == sign_code),
            sign_code,
        )
        profile["sign"] = pretty
        await query.message.reply_text(
            f"Запомнила твой знак: {pretty} ✨\n\n"
            "Теперь можно смотреть гороскоп на сегодня или на неделю:",
            reply_markup=get_horoscope_menu_keyboard(),
        )
        return

    # ----- Мини-анкета: выбор знака -----
    if data.startswith("ANKETA_SIGN_"):
        sign_code = data.replace("ANKETA_SIGN_", "")
        pretty = next(
            (label for (label, code) in ZODIAC_SIGNS if code == sign_code),
            sign_code,
        )
        profile["sign"] = pretty
        user_data["anketa_state"] = "ASK_FOCUS"
        await query.message.reply_text(
            f"Записала: {pretty} ♡\n\n"
            "И последний вопрос: что тебе сейчас интереснее всего?",
            reply_markup=get_focus_inline_keyboard(),
        )
        return

    # ----- Мини-анкета: выбор фокуса -----
    if data.startswith("FOCUS_"):
        focus_map = {
            "FOCUS_HORO": "Гороскоп и энергия дня",
            "FOCUS_LIFE": "Советы по жизни",
            "FOCUS_MONEY": "Финансы и ресурсы",
            "FOCUS_SUPPORT": "Аффирмации и поддержка",
        }
        profile["focus"] = focus_map.get(data, "что-то своё")
        user_data["anketa_state"] = None

        name = profile.get("name") or "ты"
        sign = profile.get("sign") or "твой знак"
        focus = profile.get("focus")

        text = (
            "Готово 💫\n"
            f"Я запомнила тебя:\n"
            f"• Имя: {name}\n"
            f"• Знак: {sign}\n"
            f"• Запрос: {focus}\n\n"
            "Теперь мои ответы будут чуть более «под тебя» 💌"
        )
        keyboard = InlineKeyboardMarkup(
            [
                [
                    InlineKeyboardButton(
                        "🎴 Получить персональную неделю",
                        callback_data="UTIL_PERSONAL_WEEK",
                    )
                ],
                [
                    InlineKeyboardButton(
                        "📝 Пройти анкету заново", callback_data="RESTART_ANKETA"
                    )
                ],
                [
                    InlineKeyboardButton(
                        "🏠 Главное меню", callback_data="BACK_MAIN"
                    )
                ],
            ]
        )
        await query.message.reply_text(text, reply_markup=keyboard)
        return

    if data == "RESTART_ANKETA":
        user_data["anketa_state"] = "ASK_NAME"
        await query.message.reply_text(
            "Давай попробуем ещё раз 🫶\n\nКак тебя зовут?"
        )
