zodiac_buttons = [[sign] for sign in horoscopes.keys()]
keyboard = ReplyKeyboardMarkup(zodiac_buttons, resize_keyboard=True)

async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(START_TEXT, reply_markup=keyboard)

async def message_handler(update: Update, context: ContextTypes.DEFAULT_TYPE):
    text = update.message.text
    if text in horoscopes:
        await update.message.reply_text(horoscopes[text])
    else:
        await update.message.reply_text("Выбери знак с кнопок ниже 😌")

def main():
    application = ApplicationBuilder().token(BOT_TOKEN).build()

    application.add_handler(CommandHandler("start", start))
    application.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, message_handler))

    # Порт, который даёт Render
    port = int(os.getenv("PORT", "8443"))

    # webhook_url = https://твоё_имя.onrender.com/ТОКЕН
    hook_url = f"{WEBHOOK_URL.rstrip('/')}/{BOT_TOKEN}"

    print(f"Запускаю webhook на порту {port}")
    print(f"Webhook URL: {hook_url}")

    application.run_webhook(
        listen="0.0.0.0",
        port=port,
        url_path=BOT_TOKEN,
        webhook_url=hook_url,
    )

if __name__ == "__main__":
    main()
