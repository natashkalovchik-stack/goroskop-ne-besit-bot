async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    user_data = context.user_data
    user_data.setdefault("wishes", [])
    await update.message.reply_text(
        START_TEXT,
        reply_markup=get_main_menu_keyboard(),
    )


async def send_main_menu_message(
    update: Update, context: ContextTypes.DEFAULT_TYPE, text: str
) -> None:
    if update.callback_query:
        query = update.callback_query
        await query.message.reply_text(text, reply_markup=get_main_menu_keyboard())
        await query.answer()
    else:
        await update.message.reply_text(
            text, reply_markup=get_main_menu_keyboard()
        )


async def handle_main_menu_message(
    update: Update, context: ContextTypes.DEFAULT_TYPE
) -> None:
    user_data = context.user_data
    text = update.message.text.strip()

    # Приоритетные режимы ожидания
    if user_data.get("awaiting_magic_question"):
        await handle_magic_question_text(update, context)
        return

    if user_data.get("awaiting_wish"):
        await handle_wish_text(update, context)
        return

    anketa_state = user_data.get("anketa_state")
    if anketa_state:
        await handle_anketa_text(update, context, anketa_state)
        return

    # Главное меню по тексту
    if text == "🔮 Гороскоп":
        await update.message.reply_text(
            "🔮 Гороскоп\n\nВыбери, как будем смотреть:",
            reply_markup=get_horoscope_menu_keyboard(),
        )
        return

    if text == "📝 Мини-анкета":
        user_data["anketa_state"] = "ASK_NAME"
        await update.message.reply_text(
            "Давай познакомимся поближе 🌿\n\nКак тебя зовут? "
            "(можно просто имя или прозвище)"
        )
        return

    if text == "💡 Полезности / советы":
        await update.message.reply_text(
            "Тут живут карты дня, советы, аффирмации и немного магии 🕯",
            reply_markup=get_utils_menu_keyboard(),
        )
        return

    if text == "ℹ️ О боте":
        await update.message.reply_text(ABOUT_TEXT)
        return

    # Если текст не распознан
    await update.message.reply_text(
        "Я пока не знаю, что с этим сделать, но можем начать с меню снизу 🌸",
        reply_markup=get_main_menu_keyboard(),
    )


