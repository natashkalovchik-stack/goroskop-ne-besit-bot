# ========= ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ =========


def get_profile(user_data: Dict[str, Any]) -> Dict[str, Any]:
    return user_data.setdefault("profile", {})


def format_with_profile(template: str, user_data: Dict[str, Any]) -> str:
    profile = get_profile(user_data)
    name = profile.get("name") or "ты"
    sign = profile.get("sign") or "твой знак"
    age = profile.get("age") or ""
    try:
        return template.format(name=name, sign=sign, age=age)
    except Exception:
        return template


def choose_random_text(texts: List[str], user_data: Dict[str, Any]) -> str:
    template = random.choice(texts)
    return format_with_profile(template, user_data)


